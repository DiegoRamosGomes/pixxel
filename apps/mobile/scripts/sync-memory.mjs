#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const VAULT =
  '/home/diego/.claude/projects/-media-diego-Games-Projetos-dk-assistant/memory';
const here = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.resolve(here, '..', 'src', 'generated', 'memory-bundle.ts');

if (!fs.existsSync(VAULT)) {
  console.error('vault not found:', VAULT);
  process.exit(1);
}

const files = fs
  .readdirSync(VAULT)
  .filter((f) => f.endsWith('.md'))
  .sort();

const sections = files.map((f) => {
  const content = fs.readFileSync(path.join(VAULT, f), 'utf8').trim();
  return `## ${f}\n\n${content}`;
});

const bundle = sections.join('\n\n---\n\n');

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(
  OUT,
  `// generated by scripts/sync-memory.mjs — do not edit by hand
export const MEMORY_BUNDLE = ${JSON.stringify(bundle)};
export const MEMORY_SYNCED_AT = ${JSON.stringify(new Date().toISOString())};
export const MEMORY_FILE_COUNT = ${files.length};
`,
);

console.log(
  `synced ${files.length} files, ${bundle.length} chars → ${path.relative(process.cwd(), OUT)}`,
);
